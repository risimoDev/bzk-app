/**
 * Требования к паролю.
 *
 * Перенос из старого сайта: `validate_password()` в includes/security.php
 * требовал минимум восемь символов и по одной строчной, заглавной букве
 * и цифре. При переписывании это правило потерялось - осталась только
 * длина, и пароль «12345678» проходил. Возвращаем прежнюю строгость.
 *
 * Существующие пароли этим не затрагиваются: проверка стоит только на
 * заведении нового и смене. Старый вход по-прежнему сверяет хеш как есть.
 *
 * Файл без базы и без next - его подключают и формы, и проверочный скрипт.
 */

export const PASSWORD_MIN_LENGTH = 8;
/** bcrypt считает только первые 72 байта - длиннее принимать бессмысленно. */
export const PASSWORD_MAX_LENGTH = 72;

/** Человеку - одной строкой, что должно быть в пароле. */
export const PASSWORD_HINT =
  "Минимум 8 символов: строчная и заглавная буквы и цифра.";

/**
 * Проверяет пароль по правилам. Возвращает первую понятную ошибку или
 * `null`, если всё в порядке. Первую, а не все: список из четырёх
 * претензий разом читается хуже, чем «добавьте заглавную букву».
 */
export function checkPassword(password: string): string | null {
  if (password.length < PASSWORD_MIN_LENGTH) {
    return `Пароль короче ${PASSWORD_MIN_LENGTH} символов`;
  }
  if (password.length > PASSWORD_MAX_LENGTH) {
    return `Пароль длиннее ${PASSWORD_MAX_LENGTH} символов`;
  }
  if (!/[a-zа-яё]/.test(password)) {
    return "Добавьте строчную букву";
  }
  if (!/[A-ZА-ЯЁ]/.test(password)) {
    return "Добавьте заглавную букву";
  }
  if (!/\d/.test(password)) {
    return "Добавьте цифру";
  }
  return null;
}
