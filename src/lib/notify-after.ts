import "server-only";
import { after } from "next/server";

/**
 * Выполнить работу после того, как ответ ушёл человеку.
 *
 * Уведомления шли прямо в теле действия: ответ ждал Telegram и SMTP по
 * очереди, и при медленной почте кнопка «Оформить заказ» висела секунды.
 * `after` из Next запускает задачу, когда ответ уже отправлен, и держит
 * процесс живым, пока она не закончится.
 *
 * Ошибка задачи не должна ни ломать ответ (его уже нет), ни пропадать:
 * логируем и идём дальше. Вне запроса (скрипт, проверка) `after` бросает
 * исключение - тогда задача просто запускается сразу, без ожидания: у
 * скрипта нет «ответа», который стоило бы не задерживать.
 */
export function afterResponse(label: string, task: () => Promise<unknown>) {
  const run = async () => {
    try {
      await task();
    } catch (e) {
      console.error(`[${label}] не удалось отправить:`, e instanceof Error ? e.message : e);
    }
  };

  try {
    after(run);
  } catch {
    void run();
  }
}
