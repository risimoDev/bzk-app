/**
 * Проверка суммы прописью.
 *
 *   node --experimental-strip-types scripts/check-num2words.mjs
 *
 * Отдельно проверяются круглые тысячи и миллионы: старая функция на них
 * теряла название разряда - 100 000 превращалось в «сто».
 */
import { rublesInWords, numberToWords } from "../src/lib/num2words.ts";

const cases = [
  [0, "Ноль рублей 00 копеек"],
  [1, "Один рубль 00 копеек"],
  [2, "Два рубля 00 копеек"],
  [5, "Пять рублей 00 копеек"],
  [11, "Одиннадцать рублей 00 копеек"],
  [21, "Двадцать один рубль 00 копеек"],
  [111, "Сто одиннадцать рублей 00 копеек"],
  [525, "Пятьсот двадцать пять рублей 00 копеек"],
  [1000, "Одна тысяча рублей 00 копеек"],
  [2000, "Две тысячи рублей 00 копеек"],
  [5000, "Пять тысяч рублей 00 копеек"],
  [100000, "Сто тысяч рублей 00 копеек"],
  [200000, "Двести тысяч рублей 00 копеек"],
  [201960, "Двести одна тысяча девятьсот шестьдесят рублей 00 копеек"],
  [1000000, "Один миллион рублей 00 копеек"],
  [2500000, "Два миллиона пятьсот тысяч рублей 00 копеек"],
  [1234.5, "Одна тысяча двести тридцать четыре рубля 50 копеек"],
  [0.01, "Ноль рублей 01 копейка"],
  [0.02, "Ноль рублей 02 копейки"],
  [1250, "Одна тысяча двести пятьдесят рублей 00 копеек"],
  [40155, "Сорок тысяч сто пятьдесят пять рублей 00 копеек"],
  // Копейки должны браться после округления, а не из плавающей точки
  [0.1 + 0.2, "Ноль рублей 30 копеек"],
];

let bad = 0;
for (const [n, expected] of cases) {
  const got = rublesInWords(n);
  if (got !== expected) {
    bad++;
    console.log(`✗ ${n}\n    ждали:  ${expected}\n    вышло:  ${got}`);
  }
}

// Женский род нужен разряду тысяч: «одна тысяча», не «один тысяча»
const feminine = numberToWords(21, true);
if (feminine !== "двадцать одна") {
  bad++;
  console.log(`✗ женский род: ждали «двадцать одна», вышло «${feminine}»`);
}

console.log(bad === 0 ? `Все ${cases.length + 1} проверок прошли.` : `Ошибок: ${bad}`);
process.exit(bad === 0 ? 0 : 1);
