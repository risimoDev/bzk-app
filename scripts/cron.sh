#!/bin/sh
# Планировщик: раз в несколько минут зовёт приложение по внутренней сети.
#
# Сами задачи (напоминания CRM, сроки задач, уборка журналов) живут в
# приложении: src/app/api/cron/run. Здесь только будильник. Контейнер
# отдельный по той же причине, что и backup: у приложения нет своего
# планировщика, а ставить для этого cron на хост значило бы тащить
# настройку мимо репозитория.
#
# Расписание - простой цикл со сном, как в backup.sh: ровно по минутам оно
# не нужно, задачи идемпотентны и ничего не делают при повторе.
#
# Без CRON_SECRET приложение отвечает 404 (маршрут выключен), поэтому
# контейнер просто простаивает и пишет об этом в лог, а не падает в цикле
# перезапусков.
#
# Переменные окружения:
#   CRON_SECRET     секрет, тот же, что у приложения
#   CRON_URL        адрес маршрута (по умолчанию http://app:3000/api/cron/run)
#   CRON_INTERVAL   пауза между вызовами в секундах (по умолчанию 300)

set -u

URL="${CRON_URL:-http://app:3000/api/cron/run}"
INTERVAL="${CRON_INTERVAL:-300}"

log() { echo "[cron] $(date '+%Y-%m-%d %H:%M:%S') $*"; }

if [ -z "${CRON_SECRET:-}" ]; then
  log "CRON_SECRET не задан - планировщик выключен. Задайте его в .env и перезапустите: docker compose up -d cron app"
  # Простой без выхода: restart: unless-stopped иначе гонял бы контейнер по кругу
  while true; do sleep 3600; done
fi

log "запуск, вызываю ${URL} каждые ${INTERVAL} с"

# Приложение может ещё подниматься (depends_on ждёт здоровья, но и позже
# оно перезапускается при деплое) - ошибка вызова не повод выходить
while true; do
  # Секрет передаём заголовком, не в адресе: адреса попадают в логи.
  # --post-data "" делает запрос POST; -T - потолок ожидания: проход с
  # большим числом уведомлений идёт дольше обычного
  if OUT="$(wget -q -O - -T 120 --header "Authorization: Bearer ${CRON_SECRET}" --post-data "" "${URL}" 2>&1)"; then
    log "ответ: ${OUT}"
  else
    log "вызов не удался: ${OUT:-нет ответа}"
  fi
  sleep "${INTERVAL}"
done
